// The store texts live in store/listing.json, once. This script turns them into what each place needs, and keeps them honest:
//   node scripts/listing.mjs                 check, then write release/mt-md/store/listing.md (paste into the Chrome dashboard)
//   node scripts/listing.mjs --require-current   also fail unless the texts were confirmed for this version (used by the release scripts)
//   node scripts/listing.mjs --confirm       record that the texts and screenshots were reviewed and the dashboard updated for this version
// The Chrome Web Store API can upload and publish a package but cannot change listing text, so the dashboard paste stays a manual step.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import path from "node:path"
import { TOOLS } from "../src/toolbar.js"

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
const file = path.join(root, "store/listing.json")
const listing = JSON.parse(readFileSync(file, "utf8"))
const manifest = JSON.parse(readFileSync(path.join(root, "manifest.chrome.json"), "utf8"))
const version = manifest.version

// things a listing must mention beyond the toolbar tools; add an id here when the extension gains a feature of this kind
const CORE = ["callouts", "highlight", "diagrams", "math", "files", "setup", "themes", "keys"]

export function problems(l = listing, m = manifest) {
  const out = []
  if (l.summary.length > 132) out.push(`summary is ${l.summary.length} characters; the store allows 132`)
  const covered = new Set(l.description.features.flatMap((f) => f.covers || []))
  for (const id of [...TOOLS.map((t) => t.id), ...CORE]) if (!covered.has(id)) out.push(`no feature in the description covers "${id}"`)
  const needed = [...(m.permissions || []), ...(m.optional_host_permissions || m.host_permissions ? ["hostPermissions"] : [])]
  for (const p of needed) if (!l.justifications[p]) out.push(`permission "${p}" has no justification`)
  for (const p of Object.keys(l.justifications)) if (!["remoteCode", "dataUsage", ...needed].includes(p)) out.push(`justification "${p}" is for a permission the manifest no longer has`)
  if (/work without any setting/i.test(JSON.stringify(l))) out.push('the text claims http(s) pages "work without any setting"; other sites need Allow this site')
  return out
}

export function render(l = listing) {
  const d = l.description
  return `# ${l.name}: store texts for ${version}

Generated from store/listing.json by scripts/listing.mjs. Paste into the dashboard; do not edit this file.

## Store listing

**Name:** ${l.name}

**Summary (${l.summary.length}/132):** ${l.summary}

**Category:** ${l.category}

**Description:**

${d.intro}

${d.features.map((f) => `- ${f.text}`).join("\\n")}

${d.privacy}

${d.access}

## Privacy tab

**Single purpose:** ${l.singlePurpose}

${Object.entries(l.justifications).map(([k, v]) => `**${k}:** ${v}`).join("\\n\\n")}
`.replaceAll("\\n", "\n")
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const bad = problems()
  if (bad.length) { console.error("store texts need attention:\n  " + bad.join("\n  ")); process.exit(1) }
  if (process.argv.includes("--confirm")) {
    listing.reviewedFor = version
    writeFileSync(file, JSON.stringify(listing, null, 2) + "\n")
    console.log(`store texts confirmed for ${version}`)
  } else if (process.argv.includes("--require-current") && listing.reviewedFor !== version) {
    console.error(`The store texts were last confirmed for ${listing.reviewedFor}, but this is ${version}.
Before releasing:
  1. read store/listing.json against what changed (git log since ${listing.reviewedFor}) and edit it
  2. npm run store:assets      (new screenshots and tile; look at them)
  3. paste release/mt-md/store/listing.md into the Chrome dashboard (Store listing and Privacy tabs) and upload the screenshots
  4. npm run listing:confirm`)
    process.exit(1)
  } else {
    const out = path.join(root, "release/mt-md/store/listing.md")
    mkdirSync(path.dirname(out), { recursive: true })
    writeFileSync(out, render())
    console.log(`wrote ${path.relative(root, out)} (texts confirmed for ${listing.reviewedFor}; this is ${version})`)
  }
}
